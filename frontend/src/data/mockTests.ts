export function getPaperById(paperId: string): MockPaper | undefined {
  for (const group of EXAM_GROUPS) {
    for (const exam of group.exams) {
      const paper = exam.papers.find(p => p.id === paperId);
      if (paper) {
        const actualTotalQ = paper.sections.reduce((acc, s) => acc + s.questions.length, 0);
        return {
          ...paper,
          totalQuestions: actualTotalQ > 0 ? actualTotalQ : paper.totalQuestions,
        };
      }
    }
  }
  return undefined;
}

export function getExamById(examId: string) {
  for (const group of EXAM_GROUPS) {
    const exam = group.exams.find(e => e.id === examId);
    if (exam) return { exam, group };
  }
  return undefined;
}
